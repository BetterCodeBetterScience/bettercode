#!/usr/bin/env python3
"""Link each book figure to the notebook (and figure-maker) that generates it.

Scans ``latex/book*.tex`` for ``\\includegraphics`` references and the project
notebooks for the ``save_fig_variants`` / ``save_fig`` calls that write those
figures, then emits a mapping as JSON and Markdown into ``latex/``.

This is a first step toward pulling the figure-generation code out of the
notebooks: it tells you, for every figure in the book, which notebook owns it
(or flags the figure as externally produced -- a screenshot, hand-drawn diagram
or tool-generated DAG with no notebook source).

Usage:
    uv run python scripts/figure_atlas.py [--repo .] [--check]
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

# save_fig_variants(make_fn, "name", CHAPTER, IMAGE_DIR, ...)
VARIANTS_RE = re.compile(r"""save_fig_variants\(\s*(\w+)\s*,\s*["']([\w.-]+)["']""")
# save_fig(fig, "name", CHAPTER, ...)
SAVEFIG_HELPER_RE = re.compile(
    r"""(?<!_variants)\bsave_fig\(\s*\w+\s*,\s*["']([\w.-]+)["']\s*,\s*(\w+)"""
)
# bare fig.savefig('name.png') calls (usually ad-hoc, not book figures)
BARE_SAVEFIG_RE = re.compile(r"""\.savefig\(\s*(?:[\w.]+\s*/\s*)?["']([^"']+)["']""")
CHAPTER_RE = re.compile(r"^\s*CHAPTER\s*=\s*(\d+)", re.M)
INCLUDEGRAPHICS_RE = re.compile(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}")


def notebook_code(nb_path: Path) -> str:
    """Concatenate the source of every code cell in a notebook."""
    nb = json.loads(nb_path.read_text())
    return "\n".join(
        "".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"
    )


def figures_from_code(code: str) -> list[dict]:
    """Return the book figures a notebook's code saves via the save_fig helpers."""
    chap_m = CHAPTER_RE.search(code)
    chapter = int(chap_m.group(1)) if chap_m else None
    figs = []
    for maker, name in VARIANTS_RE.findall(code):
        figs.append({"figure": _figpath(chapter, name), "maker": maker})
    for name, chap_tok in SAVEFIG_HELPER_RE.findall(code):
        chap = int(chap_tok) if chap_tok.isdigit() else chapter
        figs.append({"figure": _figpath(chap, name), "maker": None})
    return figs


def _figpath(chapter: int | None, name: str) -> str:
    """Reconstruct the ``figures/NN/name.pdf`` path a save_fig call produces."""
    return f"figures/{chapter:02d}/{name}.pdf" if chapter is not None else name


def scan_notebooks(root: Path) -> tuple[dict[str, list[dict]], dict[str, list[str]]]:
    """Map each book figure to its notebook source(s) and collect bare savefigs."""
    sources: dict[str, list[dict]] = {}
    bare: dict[str, list[str]] = {}
    for nb in sorted(root.glob("**/*.ipynb")):
        if ".ipynb_checkpoints" in nb.parts:
            continue
        rel = nb.relative_to(root.parent).as_posix()
        code = notebook_code(nb)
        for fig in figures_from_code(code):
            entry = {"notebook": rel, "maker": fig["maker"]}
            sources.setdefault(fig["figure"], []).append(entry)
        for name in BARE_SAVEFIG_RE.findall(code):
            if not name.endswith((".pdf", ".svg")):  # ad-hoc PNG side outputs
                bare.setdefault(name, []).append(rel)
    return sources, bare


def tex_references(latex_dir: Path) -> list[dict]:
    """Return every active (uncommented) includegraphics in the book .tex files."""
    refs = []
    tex_files = sorted(latex_dir.glob("book*.tex")) + [latex_dir / "preface.tex"]
    for tex in tex_files:
        if not tex.exists():
            continue
        for i, line in enumerate(tex.read_text().splitlines(), 1):
            if line.lstrip().startswith("%"):
                continue
            for m in INCLUDEGRAPHICS_RE.finditer(line):
                refs.append({"tex": tex.name, "line": i, "figure": m.group(1)})
    return refs


def build_atlas(repo: Path) -> dict:
    """Correlate tex figure references with notebook sources."""
    sources, bare = scan_notebooks(repo / "notebooks")
    refs = tex_references(repo / "latex")

    matched, external = [], []
    used = set()
    for ref in refs:
        srcs = sources.get(ref["figure"])
        if srcs:
            matched.append({**ref, "sources": srcs})
            used.add(ref["figure"])
        else:
            external.append(ref)
    orphans = {fig: s for fig, s in sources.items() if fig not in used}
    return {
        "matched": matched,
        "external_or_manual": external,
        "notebook_figures_not_in_book": orphans,
        "bare_savefig_side_outputs": bare,
    }


def render_markdown(atlas: dict) -> str:
    """Render the atlas as a human-readable Markdown document."""
    lines = [
        "# Figure atlas",
        "",
        "Generated by `scripts/figure_atlas.py`. Maps every `\\includegraphics`",
        "reference in the book's LaTeX sources to the notebook and figure-maker",
        "function that produces it. A first step toward extracting figure-generation",
        "code from the notebooks.",
        "",
        f"- **{len(atlas['matched'])}** figures generated by a notebook",
        f"- **{len(atlas['external_or_manual'])}** figures with no notebook source "
        "(screenshots, hand-drawn diagrams, tool-generated DAGs)",
        "",
        "## Figures generated by notebooks",
        "",
        "| Figure | Notebook | Maker function | Used in |",
        "| --- | --- | --- | --- |",
    ]
    for row in sorted(atlas["matched"], key=lambda r: r["figure"]):
        for s in row["sources"]:
            maker = f"`{s['maker']}`" if s["maker"] else "`save_fig`"
            lines.append(
                f"| `{row['figure']}` | [{s['notebook']}]({_up(s['notebook'])}) "
                f"| {maker} | {row['tex']}:{row['line']} |"
            )
    lines += [
        "",
        "## Figures with no notebook source",
        "",
        "These are produced outside the notebooks (screenshots, externally drawn",
        "diagrams, or DAGs rendered by other tooling). Listed here so they are not",
        "mistaken for gaps in notebook coverage.",
        "",
        "| Figure | Used in |",
        "| --- | --- |",
    ]
    for ref in sorted(atlas["external_or_manual"], key=lambda r: r["figure"]):
        lines.append(f"| `{ref['figure']}` | {ref['tex']}:{ref['line']} |")

    if atlas["notebook_figures_not_in_book"]:
        lines += [
            "",
            "## Notebook figures not referenced in the book",
            "",
            "| Figure | Notebook |",
            "| --- | --- |",
        ]
        for fig, srcs in sorted(atlas["notebook_figures_not_in_book"].items()):
            nbs = ", ".join(s["notebook"] for s in srcs)
            lines.append(f"| `{fig}` | {nbs} |")
    lines.append("")
    return "\n".join(lines)


def _up(notebook_rel: str) -> str:
    """Relative link from latex/ up to a repo-root-relative notebook path."""
    return f"../{notebook_rel}"


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument(
        "--check",
        action="store_true",
        help="print a summary to stdout instead of writing files",
    )
    args = parser.parse_args()
    atlas = build_atlas(args.repo)

    if args.check:
        print(json.dumps(atlas, indent=2))
        return

    latex = args.repo / "latex"
    (latex / "figure_atlas.json").write_text(json.dumps(atlas, indent=2) + "\n")
    (latex / "FIGURE_ATLAS.md").write_text(render_markdown(atlas))
    print(
        f"Wrote {latex / 'figure_atlas.json'} and {latex / 'FIGURE_ATLAS.md'}\n"
        f"  {len(atlas['matched'])} notebook-generated, "
        f"{len(atlas['external_or_manual'])} external/manual figures"
    )


if __name__ == "__main__":
    main()
